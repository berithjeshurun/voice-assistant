"""Generate apps/web/src/generated/protocol.ts from amy.protocol.messages.

Run after changing the Pydantic protocol models; CI fails if the output is stale:

    python scripts/gen_protocol_ts.py
"""

from __future__ import annotations

import enum
import inspect
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pydantic import BaseModel  # noqa: E402
from pydantic.json_schema import models_json_schema  # noqa: E402

from amy.branding import PROTOCOL_VERSION  # noqa: E402
from amy.protocol import messages  # noqa: E402

OUT = ROOT / "apps" / "web" / "src" / "generated" / "protocol.ts"

# Client -> server bodies: fields with Python defaults may be omitted by the client.
INPUT_MODELS = {"TurnRequest", "ClientCommand", "ApprovalAnswer", "LockdownRequest"}


def _ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in schema["enum"])
    if "anyOf" in schema:
        parts = []
        for sub in schema["anyOf"]:
            t = _ts_type(sub)
            if t not in parts:
                parts.append(t)
        return " | ".join(parts)
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        inner = _ts_type(schema.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        value = _ts_type(extra) if isinstance(extra, dict) and extra else "unknown"
        return f"Record<string, {value}>"
    return "unknown"


def _collect() -> tuple[list[type[enum.Enum]], list[type[BaseModel]]]:
    enums: list[type[enum.Enum]] = []
    models: list[type[BaseModel]] = []
    for _, obj in inspect.getmembers(messages, inspect.isclass):
        if obj.__module__ != messages.__name__:
            continue
        if issubclass(obj, enum.Enum):
            enums.append(obj)
        elif issubclass(obj, BaseModel):
            models.append(obj)
    line = {c: inspect.getsourcelines(c)[1] for c in [*enums, *models]}
    enums.sort(key=lambda c: line[c])
    models.sort(key=lambda c: line[c])
    return enums, models


def render() -> str:
    enums, models = _collect()
    _, top = models_json_schema(
        [(m, "serialization") for m in models], ref_template="#/$defs/{model}"
    )
    defs: dict[str, Any] = top.get("$defs", {})
    out = [
        "// Generated by scripts/gen_protocol_ts.py from amy/protocol/messages.py.",
        "// Do not edit by hand.",
        "",
        f"export const PROTOCOL_VERSION = {PROTOCOL_VERSION};",
        "",
    ]
    for e in enums:
        values = " | ".join(f'"{m.value}"' for m in e)
        out += [f"export type {e.__name__} = {values};", ""]
    for m in models:
        name = m.__name__
        schema = defs[name]
        doc = (m.__doc__ or "").strip().splitlines()
        if doc and doc[0]:
            out.append(f"/** {doc[0]} */")
        out.append(f"export type {name} = {{")
        required = set(schema.get("required", []))
        for field, prop in schema.get("properties", {}).items():
            optional = name in INPUT_MODELS and field not in required
            out.append(f"  {field}{'?' if optional else ''}: {_ts_type(prop)};")
        out += ["};", ""]
    return "\n".join(out)


def main() -> int:
    text = render()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if OUT.is_file() and OUT.read_text(encoding="utf-8") == text:
        print(f"up to date: {OUT.relative_to(ROOT)}")
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
